/**
 * Build the real, downloadable PDF for a RESOLVE action. Runs entirely
 * client-side (or in any Node runtime) via pdf-lib -- no headless
 * browser, so it is safe inside Vercel's function limits.
 */
export async function generateDocumentPdf(action: Action): Promise<Uint8Array> {
  const meta = DOC_META[action.kind];
  const lines = linesFor(action.id);
  const isLicense = action.kind === "LICENSE";

  const doc = await PDFDocument.create();
  doc.setTitle(`${DOC_TITLE[action.kind]} -- ${action.id}`);
  doc.setSubject("Gallium demo output -- representative data, fictional scenario");
  doc.setProducer("Gallium");
  doc.setCreator("Gallium");
  doc.setKeywords(["gallium", "demo", "representative", action.id]);

  const font = await doc.embedFont(StandardFonts.Courier);
  const bold = await doc.embedFont(StandardFonts.CourierBold);

  const w = new Writer(doc, font, bold);
  w.newPage();

  // ---- header ----
  w.row(ISSUER, meta.issuingDept, 8, COLOR.dim, bold);
  w.down(16);
  w.textL(DOC_TITLE[action.kind], 15, COLOR.ink, bold);
  w.textR("REPRESENTATIVE", 8, COLOR.focus, bold);
  w.down(14);
  w.hr(true);
  w.down(14);

  // ---- reference block ----
  w.row(`REF ${meta.refPrefix}-${ISSUE_DATE}`, `ISSUED ${ISSUE_DATE}`, 8, COLOR.dim);
  w.down(12);
  w.row(`${CUSTOMER.focusProduct.line} / ${CUSTOMER.location}`, action.id, 8, COLOR.dim);
  w.down(18);

  // ---- intro ----
  w.paragraph(DOC_INTRO[action.kind], 9.5, COLOR.secondary);
  w.down(6);

  // ---- line items / affiliates ----
  if (isLicense) {
    const rows = deriveAffiliateRows(lines);
    w.sectionLabel(meta.lineHeading, `${rows.length}`);
    drawAffiliatesTable(w, action, rows);
  } else {
    const { rows, subtotal, units, extendedTotal } = deriveLineItems(action, lines);
    w.sectionLabel(meta.lineHeading, `${rows.length}`);
    drawLineItemTable(w, action, rows, subtotal, units, extendedTotal);
  }
  w.down(4);

  // ---- parameters ----
  w.sectionLabel("PARAMETERS");
  for (const m of action.metrics) {
    w.field(m.label, m.note ? `${m.value}  (${m.note})` : m.value, m.warn ? COLOR.critical : COLOR.ink);
  }
  if (!isLicense) {
    w.field("OBSERVED RESOLVED", `${action.recovers} of ${OBSERVED_EXPOSED}`, COLOR.focus);
  }

  if (action.warning) {
    w.down(2);
    w.paragraph(`[!] ${action.warning}`, 8, COLOR.critical);
    w.down(2);
  }

  // ---- terms ----
  w.sectionLabel("TERMS");
  for (const t of meta.terms) {
    w.field(t.k, t.v);
  }

  // ---- authorization ----
  w.sectionLabel("AUTHORIZATION");
  const sigColW = CONTENT_W / 3;
  w.ensure(50);
  const sigY = w.y;
  meta.signatories.forEach((role, i) => {
    const x = MARGIN + i * sigColW;
    w.page.drawLine({
      start: { x, y: sigY },
      end: { x: x + sigColW - 16, y: sigY },
      thickness: 0.75,
      color: COLOR.ruleStrong,
    });
    w.page.drawText(sanitizeForPdf(role), { x, y: sigY - 11, size: 7.5, font: bold, color: COLOR.ink });
    w.page.drawText("SIGN / DATE", { x, y: sigY - 21, size: 7, font, color: COLOR.dim });
  });
  w.down(40);

  drawFooters(doc, font, meta.reviewLine);

  return doc.save();
}
